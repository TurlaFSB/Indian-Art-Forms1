// 4. Initialize Exhibition
function initMuseum() {
  const container = document.getElementById('exhibition-container');
  if (container) {
    container.innerHTML = MuseumExhibition.periods.map((p, i) => renderPeriod(p, i)).join('');
  }

  initAnimations();
}

// 5. Animations
function initAnimations() {
  // Parallax Hero
  gsap.to('.hero-bg', {
    yPercent: 25,
    ease: 'none',
    scrollTrigger: {
      trigger: '#intro',
      start: 'top top',
      end: 'bottom top',
      scrub: true
    }
  });

  // Fade-in image reveals
  gsap.utils.toArray('.image-wrapper img').forEach(img => {
    gsap.fromTo(img,
      { opacity: 0.8, scale: 1.04 },
      {
        opacity: 1,
        scale: 1,
        duration: 1,
        ease: 'power2.out',
        scrollTrigger: {
          trigger: img,
          start: 'top 90%',
          toggleActions: 'play none none none'
        }
      }
    );
  });
}

// 6. Modal Functions (100% Reliable via Indices)
window.openModal = function(periodIndex, artworkIndex) {
  const period = MuseumExhibition.periods[periodIndex];
  if (!period) return;
  const art = period.artworks[artworkIndex];
  if (!art) return;

  const modal = document.getElementById('artifact-modal');
  document.getElementById('modal-image').src = art.image;
  document.getElementById('modal-badge').innerText = `ERA ${period.number} • ${period.title.toUpperCase()}`;
  document.getElementById('modal-title').innerText = art.title;
  document.getElementById('modal-meta').innerHTML = `
    <span><strong>Date:</strong> ${art.date}</span> • 
    <span><strong>Medium:</strong> ${art.medium}</span> • 
    <span><strong>Provenance:</strong> ${art.location}</span>
  `;

  let bodyHTML = `
    <div class="modal-summary-box">
      <p>${art.summary}</p>
    </div>
    <div class="modal-section">
      <h4>Curatorial Analysis</h4>
      <p>${art.description}</p>
    </div>
  `;

  if (art.significance && art.significance.length > 0) {
    bodyHTML += `
      <div class="modal-section">
        <h4>Historical & Aesthetic Significance</h4>
        <ul class="significance-list">
          ${art.significance.map(s => `<li>${s}</li>`).join('')}
        </ul>
      </div>
    `;
  }

  document.getElementById('modal-body').innerHTML = bodyHTML;

  modal.setAttribute('aria-hidden', 'false');
  gsap.fromTo(modal, { autoAlpha: 0 }, { autoAlpha: 1, duration: 0.35, ease: 'power2.out' });
};

window.closeModal = function() {
  const modal = document.getElementById('artifact-modal');
  gsap.to(modal, {
    autoAlpha: 0,
    duration: 0.25,
    ease: 'power2.in',
    onComplete: () => {
      modal.setAttribute('aria-hidden', 'true');
    }
  });
};

// Keydown ESC to close
document.addEventListener('keydown', (e) => {
  if (e.key === 'Escape') closeModal();
});


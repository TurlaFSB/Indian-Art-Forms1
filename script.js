// 2. Render Artworks for each layout
function renderArtworksForPeriod(artworks, layout, periodIndex) {
  if (!artworks || artworks.length === 0) return '';

  if (layout === 'comparison' && artworks.length >= 2) {
    return `
      <div class="museum-comparison-card">
        <div class="comp-col">
          <div class="comp-tag">GANDHARA TRADITION</div>
          <div class="image-wrapper" onclick="openModal(${periodIndex}, 0)">
            <img src="${artworks[0].image}" alt="${artworks[0].title}" loading="lazy">
            <div class="hover-overlay"><span class="btn-expand">INSPECT GANDHARA ↗</span></div>
          </div>
          <div class="museum-label">
            <strong>${artworks[0].title}</strong>
            <span class="label-sub">${artworks[0].medium} • ${artworks[0].date}</span>
          </div>
        </div>

        <div class="comp-divider">
          <span class="divider-label">VS</span>
        </div>

        <div class="comp-col">
          <div class="comp-tag">MATHURA TRADITION</div>
          <div class="image-wrapper" onclick="openModal(${periodIndex}, 1)">
            <img src="${artworks[1].image}" alt="${artworks[1].title}" loading="lazy">
            <div class="hover-overlay"><span class="btn-expand">INSPECT MATHURA ↗</span></div>
          </div>
          <div class="museum-label">
            <strong>${artworks[1].title}</strong>
            <span class="label-sub">${artworks[1].medium} • ${artworks[1].date}</span>
          </div>
        </div>
      </div>
    `;
  }

  // Standard or Archaeological or Monumental gallery
  return `
    <div class="museum-artwork-stack">
      ${artworks.map((art, artIdx) => `
        <div class="artwork-card card-index-${artIdx}">
          <div class="image-wrapper" onclick="openModal(${periodIndex}, ${artIdx})">
            <img src="${art.image}" alt="${art.title}" loading="lazy">
            <div class="hover-overlay">
              <span class="btn-expand">INSPECT MASTERPIECE ↗</span>
            </div>
            ${art.type === 'hero' ? '<div class="artwork-type-pill">KEY ARTIFACT</div>' : ''}
          </div>
          <div class="museum-label">
            <div class="label-header">
              <span class="label-accession">OBJ. ${periodIndex + 1}.${artIdx + 1}</span>
              <button class="btn-text-inspect" onclick="openModal(${periodIndex}, ${artIdx})">VIEW DETAIL ↗</button>
            </div>
            <strong>${art.title}</strong>
            <span class="label-sub">${art.date} | ${art.medium}</span>
            <p class="label-summary">${art.summary}</p>
          </div>
        </div>
      `).join('')}
    </div>
  `;
}

